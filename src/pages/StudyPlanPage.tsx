import { Link, useNavigate } from "react-router";
import { useMutation } from "@tanstack/react-query";
import { useForm, useWatch } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import { ArrowRight, CalendarPlus, LoaderCircle, Sparkles, Target } from "lucide-react";
import PageHeader from "../components/PageHeader";
import ErrorAlert from "../components/ErrorAlert";
import EmptyState from "../components/EmptyState";
import LevelBadge from "../components/LevelBadge";
import useUiStore from "../store/uiStore";
import { askAi } from "../api/client";
import { studyPlanSchema } from "../schemas/studyPlanSchema";
import type { StudyPlanFormValues } from "../schemas/studyPlanSchema";
import { Button, buttonVariants } from "@/components/ui/button";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import { cn } from "@/lib/utils";

const MAX_LENGTH = 2000;

const EXAMPLE =
    "I keep getting derivatives wrong, especially the chain rule, and my calculus exam is next week.";

function StudyPlanPage() {
    const navigate = useNavigate();
    const setSearchTerm = useUiStore((state) => state.setSearchTerm);

    const {
        register,
        handleSubmit,
        setValue,
        control,
        formState: { errors },
    } = useForm<StudyPlanFormValues>({
        resolver: zodResolver(studyPlanSchema),
        mode: "onTouched",
        defaultValues: { prompt: "" },
    });
    const length = useWatch({ control, name: "prompt" }).length;

    const studyPlan = useMutation({ mutationFn: askAi });

    const onSubmit = (values: StudyPlanFormValues): void => {
        studyPlan.mutate(values.prompt);
    };

    const findSessions = (subject: string): void => {
        setSearchTerm(subject);
        navigate("/sessions");
    };

    return (
        <div className="space-y-8">
            <PageHeader
                eyebrow="Study Planner"
                title="Plan what to study"
                description="Describe what you are stuck on. Gemini turns it into a short plan and points you to the right sessions."
            />

            <div className="grid items-start gap-6 lg:grid-cols-[420px_1fr]">
                <form
                    onSubmit={handleSubmit(onSubmit)}
                    className="space-y-5 rounded-2xl border bg-card p-6 shadow-sm lg:sticky lg:top-24"
                >
                    <div className="grid gap-2">
                        <Label htmlFor="prompt" className="text-foreground">
                            What are you studying, and where are you stuck?
                        </Label>
                        <Textarea
                            id="prompt"
                            rows={8}
                            {...register("prompt")}
                            aria-invalid={errors.prompt ? true : undefined}
                            placeholder={`e.g. ${EXAMPLE}`}
                            className="resize-y"
                        />
                        <div className="flex items-start justify-between gap-3 text-xs">
                            {errors.prompt ? (
                                <p className="text-sm text-destructive">{errors.prompt.message}</p>
                            ) : (
                                <button
                                    type="button"
                                    onClick={() => setValue("prompt", EXAMPLE, { shouldValidate: true })}
                                    className="font-medium text-primary hover:underline"
                                >
                                    Try an example
                                </button>
                            )}
                            <span
                                className={cn(
                                    "shrink-0 tabular-nums",
                                    length > MAX_LENGTH ? "text-destructive" : "text-muted-foreground"
                                )}
                            >
                                {length}/{MAX_LENGTH}
                            </span>
                        </div>
                    </div>

                    <Button
                        type="submit"
                        disabled={studyPlan.isPending}
                        className="h-10 w-full"
                    >
                        {studyPlan.isPending ? <LoaderCircle className="animate-spin" /> : <Sparkles />}
                        {studyPlan.isPending ? "Planning..." : "Make my study plan"}
                    </Button>
                    <p className="text-xs text-muted-foreground">
                        Answers are generated by AI and can be wrong. Up to 5 plans a minute.
                    </p>
                </form>

                <section aria-live="polite">
                    {studyPlan.isPending ? (
                        <div className="space-y-4 rounded-2xl border bg-card p-6 shadow-sm">
                            <p className="flex items-center gap-2 text-sm text-muted-foreground">
                                <LoaderCircle className="size-4 animate-spin" />
                                Gemini is reading your description...
                            </p>
                            <div className="h-5 w-24 animate-pulse rounded-full bg-muted" />
                            <div className="h-16 animate-pulse rounded-xl bg-muted" />
                            <div className="h-24 animate-pulse rounded-xl bg-muted" />
                        </div>
                    ) : studyPlan.isError ? (
                        <ErrorAlert message={studyPlan.error.message} />
                    ) : studyPlan.data ? (
                        <article className="rounded-2xl border bg-card p-6 shadow-sm">
                            <div className="flex flex-wrap items-center justify-between gap-3">
                                <h2 className="flex items-center gap-2 font-semibold text-foreground">
                                    <Sparkles className="size-5 text-primary" />
                                    Your study plan
                                </h2>
                                <LevelBadge level={studyPlan.data.level} />
                            </div>

                            <p className="mt-4 leading-7 text-foreground">{studyPlan.data.summary}</p>

                            <h3 className="mt-6 flex items-center gap-2 text-sm font-semibold uppercase tracking-wider text-muted-foreground">
                                <Target className="size-4" />
                                Focus on first
                            </h3>
                            <ol className="mt-3 space-y-2">
                                {studyPlan.data.focusTopics.map((topic, index) => (
                                    <li
                                        key={topic}
                                        className="flex items-center gap-3 rounded-xl bg-muted p-3 text-sm text-foreground"
                                    >
                                        <span className="flex size-6 shrink-0 items-center justify-center rounded-full bg-accent text-xs font-semibold text-primary">
                                            {index + 1}
                                        </span>
                                        {topic}
                                    </li>
                                ))}
                            </ol>

                            <div className="mt-6 flex flex-col gap-3 border-t pt-5 sm:flex-row sm:items-center sm:justify-between">
                                <p className="text-sm text-muted-foreground">
                                    Suggested subject:{" "}
                                    <span className="font-medium text-foreground">
                                        {studyPlan.data.suggestedSubject}
                                    </span>
                                </p>
                                <div className="flex flex-wrap gap-2">
                                    <Link
                                        to="/bookings"
                                        className={cn(buttonVariants({ variant: "outline" }), "h-9 px-3")}
                                    >
                                        <CalendarPlus />
                                        Request a booking
                                    </Link>
                                    <Button
                                        className="h-9 px-3"
                                        onClick={() => findSessions(studyPlan.data.suggestedSubject)}
                                    >
                                        Find {studyPlan.data.suggestedSubject} sessions
                                        <ArrowRight />
                                    </Button>
                                </div>
                            </div>
                        </article>
                    ) : (
                        <EmptyState
                            icon={Sparkles}
                            title="Your plan will appear here"
                            description="Write a few sentences about the subject and what confuses you. The more specific, the better the plan."
                        />
                    )}
                </section>
            </div>
        </div>
    );
}

export default StudyPlanPage;
